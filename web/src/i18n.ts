const dict: Record<Lang, Record<Key, string>> = { "pt-BR": pt, es, en };

export function isLang(v: string | null): v is Lang {
  return v === "pt-BR" || v === "es" || v === "en";
}

export function loadLang(): Lang {
  try {
    const saved = localStorage.getItem("findclean-lang");
    if (isLang(saved)) return saved;
  } catch {
    // Storage blocked: fall back to the default.
  }
  return "pt-BR";
}

export function makeT(lang: Lang) {
  return (key: Key, vars?: Record<string, string | number>): string => {
    let s = dict[lang][key];
    if (vars) {
      for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
    }
    return s;
  };
}

export type T = ReturnType<typeof makeT>;
